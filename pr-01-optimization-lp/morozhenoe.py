from scipy.optimize import linprog

# Целевая функция: Z = 100*x1 + 120*x2 + 115*x3 -> max
# Коэффициенты с минусом, т.к. linprog ищет минимум
c = [-100, -120, -115]

# Матрица коэффициентов левой части ограничений (A_ub * x <= b_ub)
A_ub = [
    [0.65, 0.59, 0.49],   # 0.65*x1 + 0.59*x2 + 0.49*x3 <= 525 (молоко)
    [0.55, 0.70, 0.61],   # 0.55*x1 + 0.70*x2 + 0.61*x3 <= 410 (наполнители)
    [0,    1,    0   ]    # 1*x2 <= 200 (спрос на мороженое №2)
]

# Правая часть ограничений (запасы ресурсов)
b_ub = [525, 410, 200]

# Границы переменных: x1 >= 0, x2 >= 0, x3 >= 0
bounds = [(0, None), (0, None), (0, None)]

# Решение задачи симплекс-методом
result = linprog(c, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method='highs')

# Вывод результатов
print("Результат задачи линейного программирования")
print(f"Статус: {result.message}")

print("\nОптимальный объем выпуска (кг/сутки):")
print(f"  Мороженое №1: {result.x[0]:.2f} кг")
print(f"  Мороженое №2: {result.x[1]:.2f} кг")
print(f"  Мороженое №3: {result.x[2]:.2f} кг")

# result.fun - минимальное значение, умножаем на -1 для получения максимума
print(f"\nОптимальный доход: {result.fun * (-1):.2f} ден. ед.")

print("\nПроверка использования ресурсов:")

# Фактический расход ресурсов
used_milk = 0.65 * result.x[0] + 0.59 * result.x[1] + 0.49 * result.x[2]
used_fillers = 0.55 * result.x[0] + 0.70 * result.x[1] + 0.61 * result.x[2]

print(f"  Молоко:       {used_milk:.2f} кг из {b_ub[0]:.2f} кг (запас)")
print(f"  Наполнители:  {used_fillers:.2f} кг из {b_ub[1]:.2f} кг (запас)")
print(f"  Спрос на №2:  {result.x[1]:.2f} кг из {b_ub[2]:.2f} кг (максимум)")
